"""v0.3 restricted step-graph verifier for arithmetic reasoning.

Recomputes a small acyclic graph using exact fractions. It verifies declared
arithmetic claims, input literal membership, references, and graph shape.
It CANNOT certify that a graph faithfully represents the word problem.
Never executes Python generated by a model.
"""
from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal, InvalidOperation
from fractions import Fraction
import re

from .grounding import allowed_numbers

IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z0-9_]{0,19}\Z")
DECIMAL = re.compile(r"[+-]?\d+(?:\.\d+)?\Z")
RATIONAL = re.compile(r"([+-]?\d+)/([1-9]\d*)\Z")
OPERATIONS = {"add", "subtract", "multiply", "divide"}
MAX_STEPS = 12
MAX_ABS = 10**18
MAX_DIGITS = 32


class InvalidProof(ValueError):
    """Proof does not satisfy the restricted, explicitly described contract."""


def number(value: object, *, claim: bool = False) -> Fraction:
    """Parse bounded exact decimal or (for claimed results) rational number."""
    if type(value) is not str and type(value) is not int:
        raise InvalidProof("Numbers must be decimal strings or integers")
    source = str(value)
    if len(source) > MAX_DIGITS:
        raise InvalidProof("Number too long")
    match = RATIONAL.fullmatch(source) if claim else None
    if match:
        result = Fraction(int(match[1]), int(match[2]))
    elif DECIMAL.fullmatch(source):
        try:
            result = Fraction(Decimal(source))
        except (InvalidOperation, ValueError) as exc:
            raise InvalidProof("Invalid decimal") from exc
    else:
        raise InvalidProof("Invalid number format")
    if abs(result.numerator) > MAX_ABS or result.denominator > MAX_ABS:
        raise InvalidProof("Number exceeds verifier bounds")
    return result


def format_number(n: Fraction) -> str:
    return str(n.numerator) if n.denominator == 1 else f"{n.numerator}/{n.denominator}"


@dataclass(frozen=True)
class Verification:
    valid: bool
    answer: str | None
    steps: list[dict]
    error: str | None


def verify_plan(question: str, plan: object) -> dict:
    """Exact replay of a small sequential DAG with grounded input literals.

    Input shape:
      {"steps": [{"id":"s1", "op":"add",
                  "inputs":[{"literal":"12"},{"literal":"8"}],
                  "claim":"20"}, ...], "result":"s2"}

    Each ref must point to an earlier step; there are no functions, loops or
    user-defined expressions. Rejected proofs never produce a numeric answer.
    """
    trace: list[dict] = []

    def failure(reason: str) -> dict:
        return {
            "valid": False, "answer": None, "steps": trace, "error": reason,
            "arithmetic_verified": False, "numeric_grounding_passed": False,
            "semantically_verified": False,
            "verification_scope": "Structured arithmetic proof rejected; no answer certified",
        }

    try:
        if not isinstance(question, str) or not question.strip() or len(question) > 4000:
            raise InvalidProof("question must be 1 to 4000 characters")
        if type(plan) is not dict or set(plan) != {"steps", "result"}:
            raise InvalidProof("Plan must contain exactly steps and result")
        steps = plan["steps"]
        if type(steps) is not list or not 1 <= len(steps) <= MAX_STEPS:
            raise InvalidProof(f"Plan must contain 1 to {MAX_STEPS} steps")
        if type(plan["result"]) is not str or not IDENTIFIER.fullmatch(plan["result"]):
            raise InvalidProof("Invalid final result ID")

        allowed = allowed_numbers(question)
        computed: dict[str, Fraction] = {}
        used: set[str] = set()
        for index, step in enumerate(steps):
            if type(step) is not dict or set(step) != {"id", "op", "inputs", "claim"}:
                raise InvalidProof(f"Step {index + 1}: expected exactly id, op, inputs, claim")
            name, op, inputs = step["id"], step["op"], step["inputs"]
            if type(name) is not str or not IDENTIFIER.fullmatch(name) or name in computed:
                raise InvalidProof(f"Step {index + 1}: invalid or repeated step ID")
            if type(op) is not str or op not in OPERATIONS:
                raise InvalidProof(f"Step {name}: unsupported operation")
            if type(inputs) is not list or len(inputs) != 2:
                raise InvalidProof(f"Step {name}: exactly two inputs required")
            values = []
            evidence = []
            for operand in inputs:
                if type(operand) is not dict or len(operand) != 1:
                    raise InvalidProof(f"Step {name}: input must be one literal or ref")
                if "literal" in operand:
                    value = number(operand["literal"])
                    # Negative literals are accepted when the magnitude appears
                    # in text; this is not proof of sign or operator semantics.
                    if value not in allowed and abs(value) not in allowed:
                        raise InvalidProof(f"Step {name}: ungrounded literal {format_number(value)}")
                    evidence.append({"literal": format_number(value), "lexically_grounded": True})
                elif "ref" in operand:
                    ref = operand["ref"]
                    if type(ref) is not str or ref not in computed:
                        raise InvalidProof(f"Step {name}: unknown or forward reference")
                    value = computed[ref]
                    used.add(ref)
                    evidence.append({"ref": ref, "value": format_number(value)})
                else:
                    raise InvalidProof(f"Step {name}: unsupported input type")
                values.append(value)
            left, right = values
            if op == "add":
                actual = left + right
            elif op == "subtract":
                actual = left - right
            elif op == "multiply":
                actual = left * right
            else:
                if right == 0:
                    raise InvalidProof(f"Step {name}: division by zero")
                actual = left / right
            if abs(actual.numerator) > MAX_ABS or actual.denominator > MAX_ABS:
                raise InvalidProof(f"Step {name}: intermediate result exceeds bounds")
            claimed = number(step["claim"], claim=True)
            if actual != claimed:
                raise InvalidProof(f"Step {name}: claimed {format_number(claimed)} but computed {format_number(actual)}")
            computed[name] = actual
            trace.append({"id": name, "operation": op, "inputs": evidence,
                          "claimed": format_number(claimed), "recomputed": format_number(actual),
                          "claim_verified": True})

        if plan["result"] != steps[-1]["id"]:
            raise InvalidProof("Final result must be the last step")
        # Forbid unrelated 'decorative' steps: all earlier steps must feed
        # at least one downstream step (whose own lineage ends at result).
        if set(computed) - {plan["result"]} != used:
            raise InvalidProof("Plan contains an unused step")
        return {
            "valid": True, "answer": format_number(computed[plan["result"]]),
            "steps": trace, "error": None, "arithmetic_verified": True,
            "numeric_grounding_passed": True,
            "semantically_verified": False,
            "verification_scope": "Each arithmetic claim independently recomputed and literals lexically screened. The choice of operations and interpretation of the question are NOT verified.",
        }
    except InvalidProof as exc:
        return failure(str(exc))
